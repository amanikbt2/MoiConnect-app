const fs = require('fs');
const path = require('path');

const gifsDir = path.resolve(__dirname, '../assets/gifs');
const outputFile = path.resolve(__dirname, '../src/data/gifs.ts');
const supported = /\.gif$/i;

const CATEGORY_MAP = {
  applause: { title: 'Applause', category: 'Clap' },
  bye: { title: 'Waving Bye', category: 'Bye' },
  celebrate: { title: 'Celebrate', category: 'Party' },
  cheers: { title: 'Cheers Toast', category: 'Party' },
  confused: { title: 'Confused', category: 'Think' },
  cool: { title: 'Deal With It', category: 'Cool' },
  cry: { title: 'Tears Sad', category: 'Sad' },
  dance: { title: 'Victory Dance', category: 'Party' },
  fire: { title: 'Lit Fire', category: 'Fire' },
  heart: { title: 'Beating Heart', category: 'Love' },
  laugh: { title: 'Laughing', category: 'Laugh' },
  love: { title: 'In Love', category: 'Love' },
  party: { title: 'Party Time', category: 'Party' },
  shock: { title: 'Shocked', category: 'Wow' },
  thinking: { title: 'Thinking', category: 'Think' },
  thumbsup: { title: 'Thumbs Up', category: 'Agree' },
  wow: { title: 'Mind Blown', category: 'Wow' },
  yes: { title: 'Yes Exactly', category: 'Agree' }
};

const toId = (file) => path.basename(file, path.extname(file))
  .trim()
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-+|-+$/g, '') || 'gif';

const toTitle = (id) => id.split('-').filter(Boolean)
  .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
  .join(' ');

const files = fs.readdirSync(gifsDir)
  .filter((file) => supported.test(file))
  .sort((a, b) => a.localeCompare(b));

const lines = [
  '// Auto-generated by scripts/generate-gif-manifest.js. Do not edit manually.',
  '',
  'export interface GifAsset {',
  '  id: string;',
  '  title: string;',
  '  category: string;',
  '  source: any;',
  '  fileName: string;',
  '}',
  '',
  'export const GIFS: GifAsset[] = ['
];

for (const file of files) {
  const id = toId(file);
  const meta = CATEGORY_MAP[id] || { title: toTitle(id), category: 'All' };
  lines.push(`  {`);
  lines.push(`    id: '${id}',`);
  lines.push(`    title: '${meta.title}',`);
  lines.push(`    category: '${meta.category}',`);
  lines.push(`    source: null,`);
  lines.push(`    fileName: '${file}'`);
  lines.push(`  },`);
}

lines.push('];', '');
lines.push('export const GIF_SOURCES: Record<string, any> = Object.fromEntries(');
lines.push('  GIFS.flatMap((gif) => [');
lines.push('    [gif.id, gif.source],');
lines.push(`    ['gif_' + gif.id, gif.source],`);
lines.push(`    ['gif-' + gif.id, gif.source],`);
lines.push(`    [gif.fileName, gif.source]`);
lines.push('  ])');
lines.push(');');
lines.push('');
lines.push('export function getLocalGifSource(keyOrUrl?: string): any {');
lines.push('  if (!keyOrUrl || typeof keyOrUrl !== \'string\') return null;');
lines.push('  const trimmed = keyOrUrl.trim();');
lines.push('  if (GIF_SOURCES[trimmed]) return GIF_SOURCES[trimmed];');
lines.push('  const base = pathBase(trimmed);');
lines.push('  if (GIF_SOURCES[base]) return GIF_SOURCES[base];');
lines.push('  return null;');
lines.push('}');
lines.push('');
lines.push('function pathBase(val: string): string {');
lines.push('  const parts = val.split(/[\\\\/]/);');
lines.push('  return parts[parts.length - 1] || \'\';');
lines.push('}');
lines.push('');

fs.writeFileSync(outputFile, lines.join('\n'), 'utf8');
console.log(`Generated ${files.length} offline GIF assets in ${outputFile}.`);
