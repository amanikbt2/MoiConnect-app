const fs = require('fs');
const path = require('path');

const stickersDir = path.resolve(__dirname, '../assets/stickers');
const outputFile = path.resolve(__dirname, '../src/data/stickers.ts');
const supported = /\.(png|jpe?g|webp)$/i;

const toId = (file) => path.basename(file, path.extname(file))
  .trim()
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-+|-+$/g, '') || 'sticker';

const toLabel = (id) => id.split('-').filter(Boolean)
  .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
  .join(' ');

const files = fs.readdirSync(stickersDir)
  .filter((file) => supported.test(file))
  .sort((a, b) => a.localeCompare(b));

const lines = [
  '// Auto-generated by scripts/generate-sticker-manifest.js. Do not edit manually.',
  'export type StickerAsset = { id: string; label: string; source: any };',
  'export const STICKERS: StickerAsset[] = ['
];

for (const file of files) {
  const id = toId(file);
  const label = toLabel(id).replace(/'/g, "\\'");
  lines.push(`  { id: '${id}', label: '${label}', source: require('../../assets/stickers/${file}') },`);
}

lines.push('];', '');
fs.writeFileSync(outputFile, lines.join('\n'), 'utf8');
console.log(`Generated ${files.length} sticker assets.`);
